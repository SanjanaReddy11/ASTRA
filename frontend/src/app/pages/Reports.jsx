import { useState, useEffect } from "react";
import { jsPDF } from "jspdf";
import Icon from "../components/Icon.jsx";
import {
  reportService,
  evidenceService,
  authService,
} from "../services/store.js";

export default function Reports() {
  const [reports, setReports] = useState([]);
  const [activeReport, setActiveReport] = useState(null);
  const [datasetList, setDatasetList] = useState([]);

  useEffect(() => {
    setReports(reportService.getReports());
    setDatasetList(evidenceService.getEvidenceList());
  }, []);

  const refreshReports = () => {
    setReports(reportService.getReports());
    setDatasetList(evidenceService.getEvidenceList());
  };

  const handleGenerateBrief = () => {
    const title = "Conjunction Screening Brief";

    const summary =
      `ASTRA CONJUNCTION SCREENING BRIEF\n\n` +
      `Generated: ${new Date().toLocaleString()}\n\n` +
      `DATASET SUMMARY\n` +
      `CDM Datasets Available: ${datasetList.length}\n` +
      `Dataset Integrity: SHA-256 verification available\n\n` +
      `MODEL\n` +
      `Model: CatBoostRegressor\n` +
      `Prediction Horizon: +1 CDM\n` +
      `Output: Future Numerical Risk\n` +
      `Classification: Low / Medium / High\n\n` +
      `MODEL PERFORMANCE\n` +
      `R²: 76.6%\n` +
      `MAE: 3.20\n` +
      `RMSE: 4.78\n` +
      `High-Risk Recall: 77.96%\n` +
      `Weighted F1: 86.06%\n\n` +
      `RISK CLASSIFICATION\n` +
      `Low Risk: 50.56%\n` +
      `Medium Risk: 17.17%\n` +
      `High Risk: 32.27%\n\n` +
      `WORKFLOW\n` +
      `CDM ingestion → validation → preprocessing → ` +
      `CatBoost future-risk prediction → risk classification → ` +
      `alert generation → report generation`;

    const newReport = reportService.addReport(
      title,
      "TXT",
      summary
    );

    setReports(reportService.getReports());
    setActiveReport(newReport);
  };

  const handleGenerateReport = () => {
    const title = "Comprehensive Conjunction Risk Report";

    const summary =
      `ASTRA COMPREHENSIVE CONJUNCTION RISK REPORT\n\n` +
      `Generated: ${new Date().toLocaleString()}\n\n` +
      `1. DATA INTAKE\n` +
      `CDM datasets available: ${datasetList.length}\n` +
      `Dataset integrity is verified using SHA-256 where available.\n\n` +
      `2. PREDICTION MODEL\n` +
      `Model: CatBoostRegressor\n` +
      `Prediction target: Future numerical risk\n` +
      `Prediction horizon: +1 CDM\n\n` +
      `3. MODEL PERFORMANCE\n` +
      `R²: 76.6%\n` +
      `MAE: 3.20\n` +
      `RMSE: 4.78\n` +
      `High-Risk Recall: 77.96%\n` +
      `Weighted F1: 86.06%\n\n` +
      `4. RISK CLASSIFICATION\n` +
      `Low: 50.56%\n` +
      `Medium: 17.17%\n` +
      `High: 32.27%\n\n` +
      `5. PROCESSING PIPELINE\n` +
      `Uploaded → Validated → Preprocessed → ` +
      `Future-Risk Prediction → Risk Classification → ` +
      `Alert Generation → Report\n\n` +
      `6. INTEGRITY\n` +
      `SHA-256 is used to verify the integrity of uploaded CDM datasets.\n\n` +
      `7. SYSTEM\n` +
      `ASTRA satellite conjunction early-warning system.\n` +
      `Prediction engine: CatBoostRegressor.\n`;

    const newReport = reportService.addReport(
      title,
      "PDF",
      summary
    );

    setReports(reportService.getReports());
    setActiveReport(newReport);
  };

  const createPDF = (report, currentUser) => {
    const doc = new jsPDF({
      orientation: "portrait",
      unit: "mm",
      format: "a4",
    });

    const pageWidth = doc.internal.pageSize.getWidth();
    const pageHeight = doc.internal.pageSize.getHeight();

    const margin = 18;
    const textWidth = pageWidth - margin * 2;

    let y = 20;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(20);
    doc.text("ASTRA", margin, y);

    y += 8;

    doc.setFontSize(13);
    doc.setFont("helvetica", "normal");
    doc.text(
      "Conjunction Risk Report",
      margin,
      y
    );

    y += 10;

    doc.setDrawColor(60, 130, 230);
    doc.line(
      margin,
      y,
      pageWidth - margin,
      y
    );

    y += 10;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);
    doc.text("REPORT INFORMATION", margin, y);

    y += 7;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    doc.text(
      `Report ID: ${report.id}`,
      margin,
      y
    );

    y += 5;

    doc.text(
      `Title: ${report.title}`,
      margin,
      y
    );

    y += 5;

    doc.text(
      `Generated: ${report.date}`,
      margin,
      y
    );

    y += 5;

    doc.text(
      `Generated By: ${currentUser}`,
      margin,
      y
    );

    y += 10;

    doc.setFillColor(245, 248, 252);
    doc.setDrawColor(210, 220, 235);

    doc.roundedRect(
      margin,
      y,
      textWidth,
      36,
      2,
      2,
      "FD"
    );

    y += 8;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);

    doc.text(
      "MODEL SUMMARY",
      margin + 5,
      y
    );

    y += 6;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    doc.text(
      "Model: CatBoostRegressor",
      margin + 5,
      y
    );

    y += 5;

    doc.text(
      "Prediction Horizon: +1 CDM",
      margin + 5,
      y
    );

    y += 5;

    doc.text(
      "Target: Future Numerical Risk",
      margin + 5,
      y
    );

    y += 5;

    doc.text(
      "Classification: Low / Medium / High",
      margin + 5,
      y
    );

    y += 12;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);

    doc.text(
      "MODEL PERFORMANCE",
      margin,
      y
    );

    y += 7;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    const metrics = [
      "R²: 76.6%",
      "MAE: 3.20",
      "RMSE: 4.78",
      "High-Risk Recall: 77.96%",
      "Weighted F1: 86.06%",
    ];

    metrics.forEach((metric) => {
      doc.text(`• ${metric}`, margin + 3, y);
      y += 5;
    });

    y += 5;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);

    doc.text(
      "RISK CLASSIFICATION",
      margin,
      y
    );

    y += 7;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    doc.text(
      "Low Risk: 50.56%",
      margin + 3,
      y
    );

    y += 5;

    doc.text(
      "Medium Risk: 17.17%",
      margin + 3,
      y
    );

    y += 5;

    doc.text(
      "High Risk: 32.27%",
      margin + 3,
      y
    );

    y += 10;

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);

    doc.text(
      "REPORT SUMMARY",
      margin,
      y
    );

    y += 7;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    const summaryText =
      report.summary ||
      "Conjunction screening and future-risk prediction report.";

    const lines = doc.splitTextToSize(
      summaryText,
      textWidth
    );

    lines.forEach((line) => {
      if (y > pageHeight - 25) {
        doc.addPage();
        y = 20;
      }

      doc.text(line, margin, y);
      y += 4.5;
    });

    y += 7;

    if (y > pageHeight - 35) {
      doc.addPage();
      y = 20;
    }

    doc.setFont("helvetica", "bold");
    doc.setFontSize(10);

    doc.text(
      "DATA INTEGRITY",
      margin,
      y
    );

    y += 7;

    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);

    const integrityText =
      "SHA-256 dataset integrity verification is supported for uploaded CDM datasets.";

    const integrityLines = doc.splitTextToSize(
      integrityText,
      textWidth
    );

    integrityLines.forEach((line) => {
      doc.text(line, margin, y);
      y += 4.5;
    });

    y += 8;

    const footerText =
      "ASTRA • Satellite Conjunction Early-Warning System";

    doc.setFontSize(8);
    doc.setTextColor(100, 100, 100);

    doc.text(
      footerText,
      margin,
      pageHeight - 10
    );

    doc.text(
      `Page ${doc.getNumberOfPages()}`,
      pageWidth - margin - 15,
      pageHeight - 10
    );

    return doc;
  };

  const handleDownload = (report, format) => {
    const currentUser =
      authService.getCurrentUser()?.name ||
      "Astra User";

    if (format === "PDF") {
      const doc = createPDF(
        report,
        currentUser
      );

      const filename =
        `${report.id.toLowerCase()}_` +
        `${report.title
          .toLowerCase()
          .replace(/[^a-z0-9]/g, "_")}` +
        `.pdf`;

      doc.save(filename);

      return;
    }

    const content =
      `===========================================================\n` +
      `ASTRA CONJUNCTION RISK REPORT\n` +
      `===========================================================\n\n` +
      `Report ID: ${report.id}\n` +
      `Title: ${report.title}\n` +
      `Date: ${report.date}\n` +
      `Format: TXT\n` +
      `Generated By: ${currentUser}\n\n` +
      `-----------------------------------------------------------\n` +
      `REPORT SUMMARY\n` +
      `-----------------------------------------------------------\n\n` +
      `${
        report.summary ||
        "Conjunction screening and future-risk prediction report."
      }\n\n` +
      `-----------------------------------------------------------\n` +
      `DATA INTEGRITY\n` +
      `-----------------------------------------------------------\n\n` +
      `SHA-256 dataset integrity verification is supported\n` +
      `for uploaded CDM datasets.\n\n` +
      `-----------------------------------------------------------\n` +
      `MODEL\n` +
      `-----------------------------------------------------------\n\n` +
      `CatBoostRegressor\n` +
      `Prediction Horizon: +1 CDM\n` +
      `Future Risk Classification: Low / Medium / High\n\n` +
      `===========================================================\n` +
      `END OF ASTRA CONJUNCTION RISK REPORT\n` +
      `===========================================================`;

    const filename =
      `${report.id.toLowerCase()}_` +
      `${report.title
        .toLowerCase()
        .replace(/[^a-z0-9]/g, "_")}` +
      `.txt`;

    reportService.downloadFile(
      content,
      filename,
      "text/plain"
    );
  };

  return (
    <div>
      {/* -------------------- PAGE HEADER -------------------- */}
      <div className="page-head">
        <div>
          <h1>Conjunction Reports</h1>

          <p>
            Generate, review, download and archive
            Astra CDM screening and future-risk reports.
          </p>
        </div>

        <div
          className="actions"
          style={{
            display: "flex",
            gap: "10px",
          }}
        >
          <button
            className="btn ghost light-theme-action"
            onClick={handleGenerateBrief}
          >
            <Icon name="file" size={14} />
            Generate Brief
          </button>

          <button
            className="btn primary light-theme-primary-action"
            onClick={handleGenerateReport}
          >
            <Icon name="plus" size={14} />
            Generate Risk Report
          </button>
        </div>
      </div>

      {/* -------------------- REPORT GENERATORS -------------------- */}
      <div
        className="grid cols-2"
        style={{
          marginBottom: 20,
        }}
      >
        <div className="card hud-card">
          <div className="card-head">
            <h3>Conjunction Screening Brief</h3>

            <span className="chip info">
              TXT FORMAT
            </span>
          </div>

          <p
            style={{
              fontSize: 13,
              marginTop: 6,
              lineHeight: "1.6",
            }}
          >
            Generates a concise summary of CDM
            datasets, CatBoost prediction performance,
            future-risk classification and screening
            workflow.
          </p>

          <button
            className="btn primary light-theme-primary-action"
            style={{
              marginTop: 16,
              width: "100%",
            }}
            onClick={handleGenerateBrief}
          >
            Generate Screening Brief
          </button>
        </div>

        <div className="card hud-card">
          <div className="card-head">
            <h3>Comprehensive Risk Report</h3>

            <span className="chip success">
              PDF FORMAT
            </span>
          </div>

          <p
            style={{
              fontSize: 13,
              marginTop: 6,
              lineHeight: "1.6",
            }}
          >
            Generates a detailed report containing
            dataset information, model performance,
            future-risk classification and the Astra
            processing pipeline.
          </p>

          <button
            className="btn primary light-theme-primary-action"
            style={{
              marginTop: 16,
              width: "100%",
            }}
            onClick={handleGenerateReport}
          >
            Generate Comprehensive Risk Report
          </button>
        </div>
      </div>

      {/* -------------------- ACTIVE REPORT -------------------- */}
      {activeReport && (
        <div
          className="card hud-card"
          style={{
            marginBottom: 20,
            border: "1px solid var(--accent)",
          }}
        >
          <div className="card-head">
            <h3>
              Report Preview:{" "}
              {activeReport.title}
            </h3>

            <span className="chip success">
              {activeReport.id}
            </span>
          </div>

          <pre className="light-theme-code-panel">
            {activeReport.summary}
          </pre>

          <div
            style={{
              display: "flex",
              gap: "10px",
              marginTop: "14px",
            }}
          >
            <button
              className="btn primary light-theme-primary-action"
              onClick={() =>
                handleDownload(
                  activeReport,
                  "TXT"
                )
              }
            >
              <Icon
                name="download"
                size={14}
              />
              Download TXT
            </button>

            <button
              className="btn primary light-theme-primary-action"
              onClick={() =>
                handleDownload(
                  activeReport,
                  "PDF"
                )
              }
            >
              <Icon
                name="download"
                size={14}
              />
              Download PDF
            </button>
          </div>
        </div>
      )}

      {/* -------------------- REPORT ARCHIVE -------------------- */}
      <div className="card hud-card">
        <div className="card-head">
          <h3>Saved Conjunction Reports</h3>

          <span className="chip">
            {reports.length} REPORTS
          </span>
        </div>

        <div className="table-wrap">
          <table className="data">
            <thead>
              <tr>
                <th>Report ID</th>
                <th>Report Title</th>
                <th>Date Generated</th>
                <th>File Size</th>
                <th>Format</th>
                <th>Actions</th>
              </tr>
            </thead>

            <tbody>
              {reports.length === 0 ? (
                <tr>
                  <td
                    colSpan="6"
                    style={{
                      textAlign: "center",
                      padding: "30px",
                      color:
                        "var(--text-muted)",
                    }}
                  >
                    No reports generated yet.
                  </td>
                </tr>
              ) : (
                reports.map((report) => (
                  <tr key={report.id}>
                    <td
                      className="mono"
                      style={{
                        fontWeight: 700,
                        color:
                          "var(--accent)",
                      }}
                    >
                      {report.id}
                    </td>

                    <td>
                      <b>{report.title}</b>
                    </td>

                    <td className="mono">
                      {report.date}
                    </td>

                    <td className="mono">
                      {report.size}
                    </td>

                    <td>
                      <span className="chip info">
                        {report.format}
                      </span>
                    </td>

                    <td>
                      <div
                        style={{
                          display: "flex",
                          gap: "6px",
                        }}
                      >
                        <button
                          className="btn ghost light-theme-action"
                          style={{
                            padding:
                              "4px 8px",
                            fontSize: 11,
                          }}
                          onClick={() => {
                            setActiveReport(
                              report
                            );
                          }}
                        >
                          View
                        </button>

                        <button
                          className="btn ghost light-theme-action"
                          style={{
                            padding:
                              "4px 8px",
                            fontSize: 11,
                          }}
                          onClick={() =>
                            handleDownload(
                              report,
                              "TXT"
                            )
                          }
                        >
                          Download TXT
                        </button>

                        <button
                          className="btn primary light-theme-primary-action"
                          style={{
                            padding:
                              "4px 8px",
                            fontSize: 11,
                          }}
                          onClick={() =>
                            handleDownload(
                              report,
                              "PDF"
                            )
                          }
                        >
                          Download PDF
                        </button>
                      </div>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* -------------------- REPORT PIPELINE -------------------- */}
      <div
        className="card hud-card"
        style={{
          marginTop: 20,
          borderColor:
            "var(--accent-border)",
        }}
      >
        <div className="card-head">
          <h3>
            <Icon
              name="activity"
              size={16}
            />{" "}
            Report Generation Pipeline
          </h3>

          <span className="chip info">
            ASTRA
          </span>
        </div>

        <div
          style={{
            display: "grid",
            gridTemplateColumns:
              "repeat(5, 1fr)",
            gap: 12,
          }}
        >
          {[
            "CDM Upload",
            "Validation",
            "CatBoost Prediction",
            "Risk Classification",
            "Report",
          ].map((step, index) => (
            <div
              key={step}
              className="light-theme-panel"
            >
              <div className="k-label">
                0{index + 1}
              </div>

              <div
                style={{
                  marginTop: 5,
                  fontSize: 12,
                  fontWeight: 600,
                }}
              >
                {step}
              </div>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}